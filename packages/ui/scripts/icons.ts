interface IconSet {
  width?: number
  height?: number
  icons: Record<string, { body: string; width?: number; height?: number }>
}

const require = createRequire(import.meta.url)
const set: IconSet = JSON.parse(
  readFileSync(require.resolve('@iconify-json/solar/icons.json'), 'utf8'),
)
const { version } = JSON.parse(
  readFileSync(require.resolve('@iconify-json/solar/package.json'), 'utf8'),
) as { version: string }

/** SVG markup as JSX: `stroke-width` becomes `strokeWidth`, and so on. */
const toJsx = (body: string) =>
  body
    .replace(
      / ([a-z]+(?:-[a-z]+)+)=/g,
      (_, name: string) =>
        ` ${name.replace(/-([a-z])/g, (__, letter: string) => letter.toUpperCase())}=`,
    )
    .replace(/\/>/g, ' />')

/** How many elements the markup has at its top level: more than one needs a fragment. */
const roots = (body: string) => {
  let depth = 0
  let count = 0
  for (const [tag] of body.matchAll(/<\/?[a-z][^>]*>/gi)) {
    if (tag.startsWith('</')) depth--
    else {
      if (depth === 0) count++
      if (!tag.endsWith('/>')) depth++
    }
  }
  return count
}

const entries = Object.entries(ICONS).map(([name, solar]) => {
  const icon = set.icons[solar]
  if (!icon) throw new Error(`no Solar icon called ${solar}`)
  if ((icon.width ?? set.width ?? 24) !== 24 || (icon.height ?? set.height ?? 24) !== 24) {
    throw new Error(`${solar} is not drawn on the 24-unit grid`)
  }
  // An id would be shared by every copy of the icon on a page.
  if (/\bid=/.test(icon.body)) throw new Error(`${solar} defines ids`)
  const jsx = toJsx(icon.body)
  return `  /** solar:${solar} */\n  '${name}': ${roots(icon.body) > 1 ? `<>${jsx}</>` : jsx},`
})

const out = fileURLToPath(new URL('../src/solar.tsx', import.meta.url))
writeFileSync(
  out,
  `// Generated by scripts/icons.ts from @iconify-json/solar ${version}. Do not edit.
// Solar icons by 480 Design, CC BY 4.0: https://www.figma.com/community/file/1166831539721848736

export const SOLAR = {
${entries.join('\n')}
}
`,
)
execFileSync(
  process.execPath,
  [require.resolve('@biomejs/biome/bin/biome'), 'check', '--write', out],
  {
    stdio: 'inherit',
  },
)
console.info(`wrote ${Object.keys(ICONS).length} icons to ${out}`)
